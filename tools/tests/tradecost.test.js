eq('contract note: buy ₹1,997.40', side('1997.40', true), '₹5.00 ₹0.06 ₹0.00 ₹0.00 ₹0.91 ₹2.00 ₹0.00 ₹2,005.37');
eq('contract note: sell ₹2,198.60', side('2198.60', false), '₹5.00 ₹0.07 ₹0.00 ₹0.00 ₹0.91 ₹2.00 ₹0.00 ₹2,190.62');
eq('contract notes as one round trip', sum(T('1997.40', '2198.60', 1, 1, 1, false)), '₹15.95 | ₹185.25 | ₹37.85 | ₹1.51 | ₹145.89 | ₹55.31');
