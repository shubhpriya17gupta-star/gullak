// Runs the trade-cost engine from site/TradeCost.dc.html against methodology vectors G24-G28 (F13).
const fs = require('fs'), path = require('path');
const html = fs.readFileSync(path.join(__dirname, '../../site/TradeCost.dc.html'), 'utf8');
const js = html.match(/data-dc-script[^>]*>([\s\S]*?)<\/script>/)[1].split('class Component extends DCLogic')[0];
const m = new Function(js + '\nreturn {tradeCost,orderBrokerage,sideCharges,parsePrice,parseCount,rs};')();
let fail = 0;
const eq = (n, a, b) => { const ok = String(a) === String(b); if (!ok) fail++; console.log(ok ? 'PASS' : 'FAIL', n, '| got', a, '| want', b); };
const T = (buy, sell, q, nb, ns, long) => m.tradeCost(m.parsePrice(buy).v, m.parsePrice(sell).v, BigInt(q), BigInt(nb), BigInt(ns), long);
const sum = (r) => [r.charges, r.profitAfter, r.tax, r.cess, r.keep, r.total].map(m.rs).join(' | ');
eq('G24 short profit', sum(T('500', '600', 100, 1, 1, false)), '₹169.32 | ₹9,830.68 | ₹1,988.14 | ₹79.53 | ₹7,763.01 | ₹2,236.99');
eq('G25 long profit', sum(T('500', '600', 100, 1, 1, true)), '₹169.32 | ₹9,830.68 | ₹1,242.59 | ₹49.70 | ₹8,538.39 | ₹1,461.61');
eq('G26 loss', sum(T('600', '500', 100, 1, 1, false)), '₹170.32 | −₹10,170.32 | ₹0.00 | ₹0.00 | −₹10,170.32 | ₹170.32');
eq('G27 charges exceed profit', sum(T('500', '500.20', 100, 1, 1, false)), '₹158.96 | −₹138.96 | ₹0.00 | ₹0.00 | −₹138.96 | ₹158.96');
eq('G28 partial fills long', sum(T('250.55', '310.40', 1000, 3, 2, true)), '₹737.98 | ₹59,112.02 | ₹7,459.13 | ₹298.37 | ₹51,354.52 | ₹8,495.48');
eq('G29 small orders', sum(T('500', '600', 10, 1, 1, false)), '₹25.39 | ₹974.61 | ₹197.12 | ₹7.88 | ₹769.61 | ₹230.39');
eq('G30 tiny orders, 2.5% limit', sum(T('100', '150', 1, 1, 1, false)), '₹7.38 | ₹42.62 | ₹8.52 | ₹0.34 | ₹33.76 | ₹16.24');
eq('G31 mid orders', sum(T('1000', '1100', 10, 1, 1, false)), '₹48.57 | ₹951.43 | ₹194.49 | ₹7.78 | ₹749.16 | ₹250.84');
const B = (v, n) => { const b = m.orderBrokerage(m.parsePrice(v).v, BigInt(n || 1)); return m.rs(b.total) + ' ' + b.rule; };
eq('screenshot example buy ₹40,000', B('40000'), '₹20.00 cap');
eq('screenshot example sell ₹42,000', B('42000'), '₹20.00 cap');
eq('exactly ₹20,000 -> ₹20', B('20000'), '₹20.00 cap');
eq('₹19,990 -> 0.1% = ₹19.99', B('19990'), '₹19.99 pct');
eq('₹12,345.67 -> ₹12.35', B('12345.67'), '₹12.35 pct');
eq('₹5,000 -> ₹5 (0.1% equals minimum)', B('5000'), '₹5.00 pct');
eq('₹800 -> ₹5 minimum', B('800'), '₹5.00 min');
eq('₹200 -> ₹5 (2.5% equals ₹5)', B('200'), '₹5.00 min');
eq('₹150 -> 2.5% = ₹3.75', B('150'), '₹3.75 limit');
eq('₹1 -> 2.5% = ₹0.03', B('1'), '₹0.03 limit');
eq('₹1,00,000 in 3 parts -> ₹20 each', B('100000', 3), '₹60.00 cap');
eq('₹9,000 in 3 parts -> ₹5 each', B('9000', 3), '₹15.00 min');
